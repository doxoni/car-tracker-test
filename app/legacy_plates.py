# -*- coding: utf-8 -*-
"""Госномера в едином виде: АА1111АА (украинский формат).

Перенесено из старого проекта без изменений: номера машины вводят
по-разному — латиницей (AA1234BB), кириллицей (АА1234АА), с
пробелами или без. Чтобы во всех списках номер выглядел одинаково,
приводим его к одному виду: две буквы, четыре цифры, две буквы.

Правило:
- латинские буквы, похожие на кириллицу (A B C E H I K M O P T X Y),
  превращаются в кириллицу (I → І, Y → У);
- пробелы, дефисы и точки убираются;
- всё приводится к верхнему регистру;
- если номер не похож на АА1111АА (например, старый А123ВС77 или
  номер другой страны), он не ломается — просто приводится к
  верхнему регистру без разделителей.
"""

import re

# Латинская буква → кириллица (только те, что выглядят одинаково).
_LATIN_TO_CYRILLIC = str.maketrans(
    {
        "A": "А",
        "B": "В",
        "C": "С",
        "E": "Е",
        "H": "Н",
        "I": "І",
        "K": "К",
        "M": "М",
        "O": "О",
        "P": "Р",
        "T": "Т",
        "X": "Х",
        "Y": "У",
        "a": "А",
        "b": "В",
        "c": "С",
        "e": "Е",
        "h": "Н",
        "i": "І",
        "k": "К",
        "m": "М",
        "o": "О",
        "p": "Р",
        "t": "Т",
        "x": "Х",
        "y": "У",
    }
)

# Номер в формате АА1111АА: буква, буква, четыре цифры, буква, буква.
_UK_PATTERN = re.compile(r"^([А-ЯІЇЄҐЎ]{2})(\d{4})([А-ЯІЇЄҐЎ]{2})$")

# Более свободный вид номера: 1-2 буквы, 4 цифры, 0-2 буквы.
_PLATE_SHAPE = re.compile(r"^([А-ЯІЇЄҐЎ]{1,2})(\d{4})([А-ЯІЇЄҐЎ]{0,2})$")


def normalize_plate(plate: str) -> str:
    """Приводит номер к виду АА1111АА (без пробелов, кириллицей).

    Если номер не в формате АА1111АА — возвращает его в верхнем
    регистре без пробелов и тире (например, А123ВС77).
    """
    if not plate:
        return ""
    text = str(plate).strip().upper()
    text = text.translate(_LATIN_TO_CYRILLIC)
    # Убираем пробелы, дефисы, точки и прочие разделители.
    text = re.sub(r"[\s\-.]+", "", text)
    match = _UK_PATTERN.match(text)
    if match:
        return f"{match.group(1)}{match.group(2)}{match.group(3)}"
    return text


def format_plate(plate: str) -> str:
    """Номер для показа: АА 1111 АА — с пробелами.

    Номера короче стандартных (например «АА1111А») тоже показываем
    полностью, просто с теми же пробелами: «АА 1111 А».
    """
    normalized = normalize_plate(plate)
    if not normalized:
        return ""
    match = _PLATE_SHAPE.match(normalized)
    if match:
        parts = [part for part in match.groups() if part]
        return " ".join(parts)
    return normalized
