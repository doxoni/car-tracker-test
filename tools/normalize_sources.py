# Строки, которые встречаются в тестовых данных (в базе), их не трогаем.
SKIP = ("Іван Петренко", "Петро Іванов", "Олексій Ковальчук", "Микола Шевчук")


def load_map() -> dict:
    """Собрать полную карту украинский -> русский."""
    mapping = {}
    for name in ("i18n_uk_to_ru.json", "i18n_uk_to_ru_extra.json"):
        path = os.path.join(TOOLS, name)
        with open(path, encoding="utf-8") as handle:
            mapping.update(json.load(handle))
    for uk, ru in EXTRA.items():
        if uk not in mapping:
            mapping[uk] = ru
    return mapping


def main() -> int:
    """Заменить украинские строки на русские во всех исходниках."""
    mapping = load_map()
    # Длинные строки меняем первыми, чтобы короткие не испортили результат.
    items = sorted(mapping.items(), key=lambda pair: -len(pair[0]))

    total = 0
    for path in FILES:
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as handle:
            source = handle.read()
        original = source
        for uk, ru in items:
            if uk in SKIP or uk == ru:
                continue
            source = source.replace(uk, ru)
        if source != original:
            count = sum(original.count(uk) for uk, _ in items)
            with open(path, "w", encoding="utf-8", newline="") as handle:
                handle.write(source)
            total += count
            print(f"{os.path.relpath(path, ROOT)}: заменено фрагментов {count}")

    print(f"Всего замен: {total}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
