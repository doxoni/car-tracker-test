# -*- coding: utf-8 -*-
"""Проверить, что составные подписи (метка + значение) есть в словаре.

Русские куски строк, которые склеиваются с числами и именами, должны
быть в словаре отдельными ключами - тогда клиент переведёт их.

Запуск:
    python tools/check_fragments.py
"""

import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOOLS = os.path.join(ROOT, "tools")

# Строки, которые в интерфейсе идут вместе со значением.
FRAGMENTS = [
    "· Заправки:",
    "· Обслуживание:",
    "Заправок:",
    "Обслуживаний:",
    "Потрачено:",
    "Расходы:",
    "Следующее ТО:",
    "Всего машин:",
    "Общие расходы:",
    "Пробег:",
    "В бочке:",
    "Ошибка:",
    "Ошибка сети:",
    "Записано, но не выложено:",
    "Не удалось удалить:",
    "Не удалось удалить отчёт:",
    "Не вдалось удалить:",
    "Не вдалось скачать:",
    "ушла в минус:",
    "раз(ов),",
    "осталось",
    "минус",
    "· полный бак",
    "· частично",
    "· следующее до",
    "· следующее через",
    "л · из бочки (",
    "Заправки (",
    "Обслуживание (",
    "Оплаченные отчёты (",
    " л по ",
    ", одометр ",
    "По запросу «",
    "+ Добавить «",
    "Бочка:",
    "БОЧКА:",
    "Всього:",
]


def main() -> int:
    """Показать фрагменты, которых нет в словаре."""
    with open(os.path.join(TOOLS, "i18n_dict.json"), encoding="utf-8") as handle:
        dictionary = json.load(handle)

    missing = [text for text in FRAGMENTS if text not in dictionary]
    print(f"Фрагментов: {len(FRAGMENTS)}; нет в словаре: {len(missing)}")
    for text in missing:
        print(f"  | {text}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
